#!/usr/bin/env bash
# Builds Parabolic's browser extension from extension/src (one shared source tree).
#   <outDir>/chromium/                MV3 + service worker (Chrome, Brave, Edge, Arc, Vivaldi, Opera)
#   <outDir>/firefox/                 MV3 + background scripts (Firefox 115+)
#   <outDir>/parabolic-firefox.xpi    zip of the firefox folder
# Icons are rendered from the app icon (scripts/make-icon.swift) on every build.
# Usage: scripts/build-extension.sh <outDir>
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/extension/src"
BASE="$ROOT/extension/manifest.base.json"
EXPECTED_CHROME_ID="nijlimkbdkelhlhcaodjeiccbpbcneca"
SRGB="/System/Library/ColorSync/Profiles/sRGB Profile.icc"

if [[ $# -ne 1 || -z "$1" ]]; then
  echo "usage: $0 <outDir>" >&2
  exit 64
fi
mkdir -p "$1"
OUT="$(cd "$1" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ---- Icons ------------------------------------------------------------------------------------
echo "Rendering icons…"
swift "$ROOT/scripts/make-icon.swift" "$WORK/icon.png" >/dev/null
for size in 16 32 48 128; do
  args=(-s format png -z "$size" "$size")
  [[ -f "$SRGB" ]] && args+=(--matchTo "$SRGB")
  sips "${args[@]}" "$WORK/icon.png" --out "$WORK/icon-$size.png" >/dev/null
done

# ---- Manifests --------------------------------------------------------------------------------
# manifest.base.json holds the shared fields plus per-target "chromium" / "firefox" overlays and
# the ordered background script list (Firefox lists it; Chromium's sw.js importScripts it).
write_manifest() { # <target> <dir>
  python3 -I - "$BASE" "$1" "$2" <<'PY'
import json, sys
base_path, target, out_dir = sys.argv[1:4]
with open(base_path) as f:
    manifest = json.load(f)
scripts = manifest.pop("background_scripts")
overlays = {"chromium": manifest.pop("chromium"), "firefox": manifest.pop("firefox")}
manifest.update(overlays[target])
if target == "firefox":
    manifest["background"] = {"scripts": scripts}
else:
    listed = ",\n  ".join(json.dumps(s) for s in scripts)
    with open(f"{out_dir}/sw.js", "w") as f:
        f.write("// Generated by scripts/build-extension.sh — Chromium service-worker entry.\n")
        f.write(f"importScripts(\n  {listed},\n);\n")
with open(f"{out_dir}/manifest.json", "w") as f:
    json.dump(manifest, f, indent=2, ensure_ascii=False)
    f.write("\n")
PY
}

chrome_id() { # <manifest.json> — Chromium derives the ID from sha256(DER public key)
  python3 -I - "$1" <<'PY'
import base64, hashlib, json, sys
with open(sys.argv[1]) as f:
    key = json.load(f)["key"]
digest = hashlib.sha256(base64.b64decode(key)).hexdigest()[:32]
print("".join(chr(ord("a") + int(c, 16)) for c in digest))
PY
}

for target in chromium firefox; do
  dir="$OUT/$target"
  rm -rf "$dir"
  mkdir -p "$dir/icons"
  cp "$SRC"/*.js "$SRC"/*.html "$SRC"/*.css "$dir/"
  for size in 16 32 48 128; do cp "$WORK/icon-$size.png" "$dir/icons/icon-$size.png"; done
  write_manifest "$target" "$dir"
done

id="$(chrome_id "$OUT/chromium/manifest.json")"
if [[ "$id" != "$EXPECTED_CHROME_ID" ]]; then
  echo "error: Chromium extension ID is $id, expected $EXPECTED_CHROME_ID" >&2
  exit 1
fi

# ---- Firefox package --------------------------------------------------------------------------
rm -f "$OUT/parabolic-firefox.xpi"
(cd "$OUT/firefox" && zip -qr -X "$OUT/parabolic-firefox.xpi" .)

echo "Chromium: $OUT/chromium (ID $id)"
echo "Firefox:  $OUT/firefox"
echo "XPI:      $OUT/parabolic-firefox.xpi (unsigned)"
